/// Lays out `text` starting at pixel (x, y) with glyph height `size` pixels.
/// Calls `emit(px, py, w, h)` for every lit pixel rectangle. Newlines are supported.
pub fn layout(text: &str, x: f32, y: f32, size: f32, mut emit: impl FnMut(f32, f32, f32, f32)) {
    let px = size / 7.0; // pixel cell size
    let advance = px * 6.0;
    let line_h = px * 9.0;
    let mut cx = x;
    let mut cy = y;
    for c in text.chars() {
        if c == '\n' {
            cx = x;
            cy += line_h;
            continue;
        }
        let g = glyph(c);
        for (row, bits) in g.iter().enumerate() {
            // Merge horizontal runs into one quad to keep quad count low.
            let mut col = 0;
            while col < 5 {
                if bits & (0x10 >> col) != 0 {
                    let start = col;
                    while col < 5 && bits & (0x10 >> col) != 0 {
                        col += 1;
                    }
                    emit(cx + start as f32 * px, cy + row as f32 * px, (col - start) as f32 * px, px);
                } else {
                    col += 1;
                }
            }
        }
        cx += advance;
    }
}
